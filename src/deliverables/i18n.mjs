export function isSupportedLanguage(code) {
  return LANGUAGES.some((entry) => entry.code === code);
}

export function normalizeLanguage(code) {
  const value = String(code ?? "").slice(0, 2).toLowerCase();
  return isSupportedLanguage(value) ? value : "fr";
}

export function englishNameFor(code) {
  return LANGUAGES.find((entry) => entry.code === normalizeLanguage(code))?.englishName ?? "French";
}

